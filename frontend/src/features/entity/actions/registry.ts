export type EntityAliasPath = Extract<
  keyof paths,
  `/api/entities/{entity_id}/${string}`
>
export type CatalogueActionPath = Extract<keyof paths, `/api/actions/${string}`>
export type PlainActionPath =
  '/api/cosmic/soul-bind' | '/api/cosmic-resource/deposits'

export type ActionRoute =
  | { method: 'POST' | 'PUT' | 'PATCH'; path: EntityAliasPath }
  | { method: 'POST'; path: CatalogueActionPath | PlainActionPath }

export type ActionSection =
  'power' | 'arrange' | 'society' | 'war' | 'creatures' | 'beyond'

