export type RecordActionSpec = {
  id: string
  route: ActionRoute
  section: ActionSection
  self: string | null
  icon: LucideIcon
  applies: (ctx: EntityContext) => boolean
  pickers?: Record<string, PickerSpec>
  defaults?: (ctx: EntityContext) => Record<string, FieldValue>
  hidden?: readonly string[]
  omit?: (ctx: EntityContext) => readonly string[]
  labels?: Record<string, string>
  multiline?: readonly string[]
  destructive?: boolean
  confirm?: (ctx: EntityContext) => string
  blocked?: (ctx: EntityContext) => string | null
  world?: boolean
  llm?: boolean
}

const MORTAL_ROLES_HERO = new Set([
  'hero',
  'warrior',
  'knight',
  'hunter',
  'chosen',
])
const BINDABLE: readonly EntityType[] = ['item', 'vessel', 'structure']
const SETTLED: readonly EntityType[] = ['people', 'settlement']
const COMMUNITY_PICK: PickerSpec = { source: 'entity', types: COMMUNITY_TYPES }
const MORTAL_PICK: PickerSpec = { source: 'entity', types: ['mortal'] }
const DEAD_SON: PickerSpec = { source: 'son', status: 'dead' }

const is =
  (...types: EntityType[]) =>
  (ctx: EntityContext) =>
    types.includes(ctx.type)
const canonOf =
  (test: (ctx: EntityContext) => boolean) => (ctx: EntityContext) =>
    ctx.canon && test(ctx)
const livingMortal = (ctx: EntityContext) => ctx.type === 'mortal' && ctx.canon
const community = (ctx: EntityContext) => isCommunity(ctx.type) && ctx.canon
const living = (ctx: EntityContext) => isLiving(ctx.type) && ctx.canon
const hasWar = (ctx: EntityContext) => ctx.wars.length > 0
const hero = (ctx: EntityContext) =>
  livingMortal(ctx) && MORTAL_ROLES_HERO.has(ctx.entity.mortal_role ?? '')
const flagged = (flag: string) => (ctx: EntityContext) => ctx.flags.has(flag)
const will = (verb: string) => (ctx: EntityContext) =>
  `${ctx.entity.name} ${verb}`

const entityRoute = (
  path: EntityAliasPath,
  method: 'POST' | 'PUT' | 'PATCH' = 'POST'
): ActionRoute => ({ method, path })
const catalogueRoute = (path: CatalogueActionPath): ActionRoute => ({
  method: 'POST',
  path,
})

