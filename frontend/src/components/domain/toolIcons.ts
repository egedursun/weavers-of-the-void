export const TOOL_FALLBACK_ICON: LucideIcon = Wrench

export function isToolId(tool: string): tool is ToolId {
  return Object.hasOwn(TOOL_ICON, tool)
}

export function toolIdIcon(tool: string | null): LucideIcon | null {
  return tool && isToolId(tool) ? TOOL_ICON[tool] : null
}
