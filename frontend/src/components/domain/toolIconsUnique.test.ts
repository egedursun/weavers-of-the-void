describe('tool icons', () => {
  it('gives every tool from W51 on an icon no other tool uses', () => {
    const icons = Object.values(TOOL_ICON)
    const sharing = Object.entries(TOOL_ICON)
      .filter(([tool]) => !SHARED_BEFORE_W51.has(tool))
      .filter(([, icon]) => icons.filter((other) => other === icon).length > 1)
      .map(([tool]) => tool)
    expect(sharing).toEqual([])
  })

  it('keeps the list of older shared icons to tools that still share', () => {
    const icons = Object.values(TOOL_ICON)
    const alone = [...SHARED_BEFORE_W51].filter(
      (tool) =>
        !(tool in TOOL_ICON) ||
        icons.filter(
          (icon) => icon === TOOL_ICON[tool as keyof typeof TOOL_ICON]
        ).length === 1
    )
    expect(alone).toEqual([])
  })
})
