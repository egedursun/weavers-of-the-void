import argparse
import sys
from collections import defaultdict
from pathlib import Path

from aerona.engine.interconnect.catalog import REGISTERED
from aerona.engine.interconnect.edges import edge_counts, matrix
from aerona.engine.interconnect.registry import EdgeKind, Mechanic, Subsystem
from aerona.engine.interconnect.sweeps import SWEEPS, SweepClass

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "spec" / "13-interconnection.md"
CYCLE_LIMIT = 6
LISTED_LIMIT = 3


def covering(item: SweepClass) -> list[Mechanic]:
    found = []
    for mechanic in REGISTERED.values():
        text = f"{mechanic.key} {mechanic.title}".lower()
        if mechanic.subsystem in item.subsystems and (not item.words or any(word in text for word in item.words)):
            found.append(mechanic)
    return sorted(found, key=lambda mechanic: mechanic.key)


def cycles() -> list[tuple[Subsystem, ...]]:
    graph: dict[Subsystem, set[Subsystem]] = defaultdict(set)
    for source, target in matrix():
        graph[source].add(target)
    found: set[tuple[Subsystem, ...]] = set()

    def walk(start: Subsystem, node: Subsystem, path: tuple[Subsystem, ...]) -> None:
        for following in sorted(graph[node]):
            if following == start and len(path) >= 2:
                lowest = path.index(min(path))
                found.add(path[lowest:] + path[:lowest])
            elif following not in path and len(path) < LISTED_LIMIT and following > start:
                walk(start, following, (*path, following))

    for start in sorted(graph):
        walk(start, start, (start,))
    return sorted(found, key=lambda cycle: (len(cycle), cycle))


def render() -> str:
    subsystems = list(Subsystem)
    cells = matrix()
    lines = [
        "# Interconnection registry",
        "",
        "Generated by `scripts/interconnection_docs.py` from the registry (spec 13, I.1, I.2, I.3 and 1R.22).",
        "Edges come from declared couplings, from the `@reads`/`@writes` annotations (a writer's key read by another mechanic), "
        "from the modifier sources and from the per-step rule switches.",
        "",
        "## Subsystem matrix (rows affect columns, number of carriers)",
        "",
        "| from ↓ / to → | " + " | ".join(item.value for item in subsystems) + " |",
        "|---|" + "---:|" * len(subsystems),
    ]
    for source in subsystems:
        row = ["—" if source is target else str(len(cells.get((source, target), set())) or "·") for target in subsystems]
        lines.append(f"| {source.value} | " + " | ".join(row) + " |")
    counts = edge_counts()
    lines += ["", "## Edges by kind", ""]
    for kind in EdgeKind:
        lines.append(f"- {kind.value}: {counts[kind]}")
    lines += ["", f"## Feedback cycles between subsystems (length ≤ {LISTED_LIMIT} listed)", ""]
    found = cycles()
    lines += [f"- {' → '.join(item.value for item in cycle)} → {cycle[0].value}" for cycle in found]
    lines += ["", "## Class-by-class sweep listings (1R.22)", ""]
    for sweep, classes in SWEEPS.items():
        lines += [f"### {sweep}", "", "| Class | Covered by |", "|---|---|"]
        for item in classes:
            names = ", ".join(mechanic.key for mechanic in covering(item)) or "not yet covered"
            lines.append(f"| {item.code}: {item.name} | {names} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("write", "print", "check"), nargs="?", default="print")
    mode = parser.parse_args().mode
    text = render()
    if mode == "write":
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"written to {OUTPUT.relative_to(ROOT)}")
    elif mode == "check":
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/interconnection_docs.py write")
            return 1
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
