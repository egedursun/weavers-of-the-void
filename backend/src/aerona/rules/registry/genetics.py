    pool_drift_pct: int = rule(10, 0, 100, M, "How far a people's allele pool moves each epoch toward the blood of its living members (%)")
    presence_beauty_pct: int = rule(30, 0, 100, M, "How much beauty adds to presence beside social awareness (%)")
    resemblance_share: int = rule(60, 0, 100, M, "Share of a house's living blood members who must share a visible look for it to become the house's mark (%)")
    resemblance_members: int = rule(3, 1, 20, M, "Living blood members a house needs before a shared look becomes its mark")
    kin_marriage_fear: int = rule(40, 0, 200, M, "How much the inbreeding of a match puts a house off it, unless its people hold kin marriage admirable")
    kin_claim_pull: int = rule(25, 0, 200, M, "How much a house that holds kin marriage admirable seeks matches that keep a claim in the blood")


