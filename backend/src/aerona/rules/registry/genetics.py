    gene_trait_pct: int = rule(60, 0, 100, M, "Chance a newborn whose blood shows a leaning tied to a heritable trait takes that trait (%)")
    germline_trait: int = rule(10, 0, 100, M, "Strength each step of a source's blood adds to the matching trait of a living line made from it")
    giant_strength: int = rule(15, 0, 50, M, "Strength giant blood adds at birth")
    divine_charisma: int = rule(10, 0, 50, M, "Charisma divine blood adds at birth")
    potential_deviation: int = rule(10, 0, 40, M, "How far a child's inborn potential strays from the mean of its parents'")
    upbringing_pct: int = rule(20, 0, 100, M, "How much the wealth and home of the household raising a child lifts its abilities (%)")
    beauty_base: int = rule(50, 0, 100, M, "Beauty of a face its own people neither prize nor shun")
    beauty_taste_pct: int = rule(20, 0, 100, M, "How much each look the people prize or shun moves beauty (%)")
    beauty_scar: int = rule(6, 0, 50, M, "Beauty each scar takes")
    beauty_missing: int = rule(10, 0, 50, M, "Beauty each missing part takes")
    beauty_mark: int = rule(12, 0, 50, M, "Beauty each visible mark of an affliction takes")
    beauty_age_pct: int = rule(25, 0, 100, M, "Share of beauty old age wears away (%)")
    recognisable_base: int = rule(20, 0, 100, M, "Recognisability of a face with nothing unusual about it")
    recognisable_rare: int = rule(10, 0, 50, M, "Recognisability each rare visible allele adds")
    recognisable_scar: int = rule(5, 0, 50, M, "Recognisability each scar or missing part adds")
