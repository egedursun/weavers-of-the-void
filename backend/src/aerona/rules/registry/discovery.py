from dataclasses import dataclass

from aerona.rules.groups import RuleGroup
from aerona.rules.model import rule

K = RuleGroup.CIVILIZATION


@dataclass(frozen=True)
class DiscoveryRules:
    skill_divisor: int = rule(20, 1, 100, K, "Skill levels that make one point toward a great person each epoch")
    skilled_counted: int = rule(3, 1, 20, K, "Most skilled mortals of a field whose skill counts toward a great person")
    structure_points: int = rule(2, 0, 50, K, "Points toward a great person each working structure of the field adds each epoch")
    great_threshold: int = rule(60, 1, 10000, K, "Points a community gathers in a field before a great person rises")
    threshold_growth: int = rule(20, 0, 1000, K, "Points every great person already risen in the world adds to the next threshold")
    great_skill: int = rule(25, 0, 100, K, "Skill a great person gains in their field on rising")
    great_renown: int = rule(20, 0, 100, K, "Renown a great person gains on rising")
    great_morale: int = rule(15, 0, 100, K, "Morale a great general's campaign gives every army of the realm")
    great_zeal: int = rule(15, 0, 100, K, "Zeal a great prophet's doctrine gives their faith")
    great_rush: int = rule(30, 0, 100, K, "Construction progress a great engineer gives every work under way at home")
    great_wealth: int = rule(80, 0, 10000, K, "Treasury a great merchant's monopoly brings in")
    great_prestige: int = rule(10, 0, 100, K, "Prestige a great artist's work gives their tongue")
    great_charting: int = rule(40, 0, 100, K, "Map knowledge a great explorer's discovery gives of the lands around the realm")
    era_leaders: int = rule(3, 1, 50, K, "Holders with the most techniques whose knowledge sets the world's era")
    era_advance_pct: int = rule(50, 1, 100, K, "Share of the next era's techniques the leaders must know for the world to enter it (%)")
    first_points: int = rule(8, 0, 200, K, "Era score for being first in the world to know a technique")
    institution_points: int = rule(15, 0, 200, K, "Era score for being the birthplace of an institution")
    victory_points: int = rule(20, 0, 200, K, "Era score for winning a war")
    wonder_points: int = rule(25, 0, 200, K, "Era score for raising a wonder")
    great_person_points: int = rule(15, 0, 200, K, "Era score for a great person rising")
    defeat_points: int = rule(20, 0, 200, K, "Era score lost for losing a war")
    famine_points: int = rule(5, 0, 200, K, "Era score lost for each starving community")
    era_decay: int = rule(3, 0, 100, K, "Era score that fades toward nothing each epoch")
    golden_at: int = rule(60, 1, 1000, K, "Era score at which a realm enters a golden age")
    dark_at: int = rule(-40, -1000, -1, K, "Era score at which a realm falls into a dark age")
    heroic_rise: int = rule(50, 1, 1000, K, "Era score a dark realm must regain from its lowest point for a heroic age")
    golden_stability: int = rule(2, 0, 50, K, "Stability a golden or heroic age adds each epoch")
    dark_stability: int = rule(2, 0, 50, K, "Stability a dark age takes each epoch")
    golden_research_pct: int = rule(10, 0, 200, K, "Research gained in a golden age (%)")
    heroic_research_pct: int = rule(20, 0, 200, K, "Research gained in a heroic age (%)")
    dark_research_pct: int = rule(15, 0, 100, K, "Research lost in a dark age (%)")
    discovery_incident_pct: int = rule(20, 0, 100, K, "Chance a dangerous technique brings an incident when it is learned (%)")
    use_incident_pct: int = rule(4, 0, 100, K, "Chance each epoch a holder of a dangerous art suffers an incident (%)")
    accident_pct: int = rule(3, 0, 100, K, "Chance each epoch that research in a risky branch causes an accident (%)")
    incident_severity: int = rule(30, 1, 100, K, "Typical severity of a research incident")
    incident_dead_pct: int = rule(2, 0, 100, K, "Share of a community killed by a severe incident, at full severity (%)")
    incident_prosperity: int = rule(8, 0, 100, K, "Prosperity a fire or explosion burns away at full severity")
    incident_danger: int = rule(10, 0, 100, K, "Danger a loose beast adds to its region at full severity")
    leak_progress: int = rule(25, 0, 99, K, "Progress toward a leaked technique a neighbour gains")
    ethics_relation: int = rule(15, 0, 100, K, "Relation a neighbour who holds a dangerous art shameful loses with its learner")
    ethics_infamy: int = rule(5, 0, 100, K, "Infamy the ruler of a realm that learns a dangerous art gains")
    study_progress: int = rule(10, 0, 100, K, "Progress each epoch toward the technique behind a studied artefact, at full scholar skill")
    reverse_progress: int = rule(40, 0, 99, K, "Progress toward the technique a finished study gives")
    copy_scribes_pct: int = rule(5, 1, 100, K, "Share of scribes a community needs to copy a work at full pace without printing (%)")
    printed_rumour_pct: int = rule(30, 0, 100, K, "Distortion rumours are spared where printing is known (%)")
    printed_creed_pct: int = rule(30, 0, 200, K, "Spread creeds gain where printing is known (%)")
    ban_reading_pct: int = rule(20, 0, 100, K, "Chance a banned work is still read in secret each epoch (%)")
    black_market_price: int = rule(5, 0, 100, K, "Wealth a community pays smugglers for a banned work brought in from abroad")
    heresy_pct: int = rule(3, 0, 100, K, "Orthodoxy a faith loses each time a banned work reaches its faithful")
    ban_strictness: int = rule(50, 0, 100, K, "Censorship strictness at which a realm bans works of the forbidden arts and rival creeds")
    trade_charting: int = rule(15, 0, 100, K, "Map knowledge a realm holds of every region its trade roads cross")
    cartography_pct: int = rule(50, 0, 200, K, "How much faster explorers chart land and how much slower maps fade with cartography (%)")
    charted_journey_pct: int = rule(30, 0, 100, K, "Danger of a journey through well-charted land that is avoided (%)")
    charted_claim_pct: int = rule(20, 0, 200, K, "Strength a claim on well-charted land gains (%)")
    charted_level: int = rule(60, 0, 100, K, "Map knowledge from which land counts as well charted")
    blueprint_quality: int = rule(50, 0, 100, K, "Quality of a design drawn by its own makers")
    blueprint_pct: int = rule(20, 0, 200, K, "Construction, ship quality or siege progress gained from a design of the thing, at full quality (%)")
    blueprint_theft_pct: int = rule(25, 0, 100, K, "Chance a spy who steals a secret also carries off a design")
    blueprint_trade_pct: int = rule(10, 0, 100, K, "Chance each epoch a design is sold to a trade partner")
    blueprint_price: int = rule(30, 0, 10000, K, "Wealth a buyer pays for a design")
    licence_fee: int = rule(5, 0, 1000, K, "Wealth a licensee pays the design's holder each epoch")
    obsolete_pct: int = rule(20, 0, 100, K, "Output or effect an outdated method or structure loses (%)")
    refit_cost: int = rule(30, 0, 10000, K, "Wealth a community pays to refit an outdated structure or method")
