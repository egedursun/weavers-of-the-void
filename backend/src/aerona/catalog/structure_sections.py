@dataclass(frozen=True)
class PartSpec:
    section: StructureSection
    role: SectionRole
    criticality: Criticality
    share: int
    exposure: int
    hazard: SectionHazard = SectionHazard.NONE
    neighbours: tuple[StructureSection, ...] = ()


def part(
    section: StructureSection,
    role: SectionRole,
    criticality: Criticality,
    weight: tuple[int, int],
    hazard: SectionHazard = SectionHazard.NONE,
    *neighbours: StructureSection,
) -> PartSpec:
    return PartSpec(section, role, criticality, weight[0], weight[1], hazard, neighbours)


