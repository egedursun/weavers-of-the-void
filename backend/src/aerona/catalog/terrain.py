TACTIC_TERRAIN: Mapping[Tactic, frozenset[TerrainKind]] = {
    tactic: kinds for tactic in Tactic if (kinds := frozenset(kind for kind, spec in TERRAIN.items() if tactic in spec.tactics))
}


def terrain_has(kind: TerrainKind | None, *traits: TerrainTrait) -> bool:
    return kind is not None and bool(TERRAIN[kind].traits & set(traits))


def terrains(*traits: TerrainTrait, every: tuple[TerrainTrait, ...] = (), without: tuple[TerrainTrait, ...] = ()) -> frozenset[TerrainKind]:
    return frozenset(
        kind for kind, spec in TERRAIN.items() if (not traits or spec.traits & set(traits)) and set(every) <= spec.traits and not spec.traits & set(without)
    )
