IMAGE_UPLOAD_SUFFIX = "/images"
PACKAGE_UPLOAD_SUFFIX = "/world/import"
ATTACHMENT_UPLOAD_SUFFIX = "/divine-will/attachments"
LIBRARY_IMPORT_SUFFIX = "/library/imports"
LIBRARY_COVER_SUFFIX = "/cover"
UNKNOWN_ENDPOINT = "Unknown endpoint."
UNDECLARED_ROUTES = "Routes without an access declaration: {routes}"


def body_limits(configured: Settings) -> tuple[BodyLimit, ...]:
    attachments = configured.divine_will_upload_max_files * configured.divine_will_upload_max_mb * MEGABYTE + MULTIPART_OVERHEAD_BYTES
    return (
        BodyLimit(f"{API_PREFIX}{IMAGE_UPLOAD_SUFFIX}", IMAGE_UPLOAD_MAX_BYTES, binary=True),
        BodyLimit(f"{API_PREFIX}{PACKAGE_UPLOAD_SUFFIX}", PACKAGE_UPLOAD_MAX_BYTES, binary=True),
        BodyLimit(f"{API_PREFIX}{ATTACHMENT_UPLOAD_SUFFIX}", attachments, binary=False, multipart=True),
        BodyLimit(f"{API_PREFIX}{LIBRARY_IMPORT_SUFFIX}", configured.library_import_max_mb * MEGABYTE + MULTIPART_OVERHEAD_BYTES, binary=False, multipart=True),
        BodyLimit(
            LIBRARY_COVER_SUFFIX, IMAGE_UPLOAD_MAX_BYTES + MULTIPART_OVERHEAD_BYTES, binary=False, multipart=True, path_prefix=f"{API_PREFIX}{LIBRARY_PATH}/"
        ),
    )


def build_api_router() -> APIRouter:
    api = APIRouter(prefix=API_PREFIX, dependencies=[Depends(guard_writes)], responses={"default": {"model": ErrorResponse, "description": ERROR_DESCRIPTION}})
    for module in ROUTERS:
        api.include_router(module.router)

    @api.api_route("/{path:path}", methods=["GET", "POST", "PUT", "PATCH", "DELETE"], include_in_schema=False)
    async def unknown(path: str) -> None:
        raise NotFoundError(UNKNOWN_ENDPOINT)

    missing = undeclared(routes_of(api), lever_permission)
    if missing:
        raise RuntimeError(UNDECLARED_ROUTES.format(routes=", ".join(missing)))
    return api


def routes_of(api: APIRouter) -> list[APIRoute]:
    found = [route for module in ROUTERS for route in module.router.routes if isinstance(route, APIRoute)]
    found.extend(route for route in api.routes if isinstance(route, APIRoute))
    return found


def api_routes() -> list[APIRoute]:
    return routes_of(build_api_router())
