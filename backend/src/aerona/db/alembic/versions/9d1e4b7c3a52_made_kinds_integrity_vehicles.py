def rename_rules(renames: dict[tuple[str, str], str]) -> None:
    bind = op.get_bind()
    for (namespace, old), new in renames.items():
        bind.execute(
            sa.text("UPDATE rule_overrides SET key = :new WHERE namespace = :namespace AND key = :old"), {"new": new, "namespace": namespace, "old": old}
        )
    for cosmos_id, raw in bind.execute(sa.text("SELECT id, rules_snapshot FROM cosmos")).all():
        snapshot = json.loads(raw) if isinstance(raw, str) else dict(raw or {})
        changed = False
        for (namespace, old), new in renames.items():
            table = snapshot.get(namespace)
            if isinstance(table, dict) and old in table:
                table[new] = table.pop(old)
                changed = True
        if changed:
            bind.execute(sa.text("UPDATE cosmos SET rules_snapshot = :snapshot WHERE id = :id"), {"snapshot": json.dumps(snapshot), "id": cosmos_id})


