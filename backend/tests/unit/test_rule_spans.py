def rule_rows() -> list[tuple[str, str, str]]:
    rules = Rules()
    return [
        (f"{part.name}.{definition.name}", rule_meta(definition).label, rule_meta(definition).unit)
        for part in fields(rules)
        for definition in fields(getattr(rules, part.name))
    ]


def test_a_span_of_a_life_or_a_society_is_set_in_years_and_only_game_rhythm_counts_epochs() -> None:
    rows = rule_rows()
    counted = {key for key, label, unit in rows if unit != YEARS_UNIT and SPAN_IN_EPOCHS.match(label)}
    assert counted - GAME_RHYTHM == set(), f"set these spans in years with span(), or show why they pace the game: {sorted(counted - GAME_RHYTHM)}"
    assert GAME_RHYTHM - counted == set(), f"no longer counted in epochs: {sorted(GAME_RHYTHM - counted)}"


def test_a_span_in_years_becomes_more_epochs_in_a_world_of_short_epochs() -> None:
    rules = Rules()
    short = replace(rules, time=replace(rules.time, years_per_epoch=1))
    assert rules.grief.mourning_epochs == 1 and short.grief.mourning_epochs == rules.grief.mourning_years
    assert short.treaties.alliance_epochs == rules.treaties.alliance_years > rules.treaties.alliance_epochs == 1
